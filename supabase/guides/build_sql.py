"""Builds supabase/schema-9-starter-guides.sql from the guide files in this folder.
Run:  python supabase/guides/build_sql.py
"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
G = []
for f in ['levelling.py', 'level60.py', 'raids.py']:
    ns = {}
    exec(open(os.path.join(HERE, f), encoding='utf-8').read(), ns)
    G += ns['GUIDES']

KIND = {"Zul'Gurub": 'raid', "Ruins of Ahn'Qiraj": 'raid', "Onyxia's Lair": 'raid', 'Molten Core': 'raid', 'Blackwing Lair': 'raid',
        "Temple of Ahn'Qiraj": 'raid', 'Naxxramas': 'raid', 'Upper Blackrock Spire': 'raid'}

def q(s):
    return 'null' if s in (None, '') else "'" + str(s).replace("'", "''") + "'"

out = ["""-- Solitude update 9: starter guides for every Classic dungeon and raid.
-- Paste ALL of this into Supabase → SQL Editor → New query → Run.
-- Safe to run again: it only fills in guides that are missing, and never
-- overwrites tactics your group has written or edited.
-- (Generated by supabase/guides/build_sql.py, edit the .py files and re-run that to change it.)

alter table public.dungeons
  add column if not exists guide_where text,
  add column if not exists guide_overview text,
  add column if not exists guide_before text,
  add column if not exists guide_route jsonb,
  add column if not exists guide_tips text;

-- 'guide' = Solitude's starter guide, 'group' = written or edited by your group
alter table public.boss_notes add column if not exists source text not null default 'group';

create or replace function public.touch_edited()
returns trigger language plpgsql set search_path = public as $$
begin
  new.updated_at := now();
  if auth.uid() is not null and tg_table_name = 'boss_notes' then
    new.updated_by := auth.uid();
    new.source := 'group';   -- once someone edits it, it's your group's
  end if;
  return new;
end; $$;
"""]

for g in G:
    kind = KIND.get(g['name'], 'dungeon')
    out.append(f"""
-- ---------- {g['name']} ----------
insert into public.dungeons (name, kind) values ({q(g['name'])}, '{kind}') on conflict (name) do nothing;
update public.dungeons set
  guide_where = coalesce(guide_where, {q(g['where'])}),
  guide_overview = coalesce(guide_overview, {q(g['overview'])}),
  guide_before = coalesce(guide_before, {q(g['before'])}),
  guide_route = coalesce(guide_route, {q(json.dumps(g['route']))}::jsonb),
  guide_tips = coalesce(guide_tips, {q(g['tips'])})
where name = {q(g['name'])};""")
    rows = []
    for i, (boss, summary, tank, healer, dps) in enumerate(g['bosses'], start=1):
        rows.append(f"  ({q(boss)}, {i}, {q(summary)}, {q(tank)}, {q(healer)}, {q(dps)})")
    out.append(f"""insert into public.boss_notes (dungeon_id, boss, position, summary, tank, healer, dps, source, updated_by)
select d.id, v.boss, v.position, v.summary, v.tank, v.healer, v.dps, 'guide', null
from public.dungeons d, (values
{(','+chr(10)).join(rows)}
) as v(boss, position, summary, tank, healer, dps)
where d.name = {q(g['name'])}
on conflict (dungeon_id, lower(boss)) do nothing;""")

open(os.path.join(HERE, '..', 'schema-9-starter-guides.sql'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('wrote schema-9-starter-guides.sql:', len(G), 'dungeons,', sum(len(g['bosses']) for g in G), 'bosses')
